"""Decision attribution service.

This module handles the persistence of trading decisions generated by LLMs,
creating an audit trail that links decisions to source newsletters.
"""

import inspect
from typing import Any

from supabase import Client

from core.config import logger
from core.models import DecisionObject
from memory.embeddings import get_embedding


def save_decision(
    client: Client,
    decision: DecisionObject,
    status: str = "CREATED",
    metadata: dict[str, Any] | None = None,
    trade_id: str | None = None,
    decision_id: str | None = None,
) -> dict[str, Any]:
    """Save a trading decision to the database for attribution.

    Uses upsert to handle duplicate decisions idempotently. A decision is
    considered duplicate if it has the same source_id, ticker, signal,
    model_provider, and model_name. If `decision_id` is provided, updates
    the existing row exactly instead of relying on the unique constraint.

    Args:
        client: The Supabase client instance.
        decision: The DecisionObject containing the trading signal and metadata.
        status: The processing status of the decision.
        metadata: Additional context or execution info.
        trade_id: Optional ID of the executed trade (if any).
        decision_id: Optional ID of an existing decision row to update directly.

    Returns:
        The upserted or updated row data as a dictionary.

    Raises:
        Exception: If the upsert or update operation fails.
    """
    payload = {
        "source_id": decision.source_id,
        "ticker": decision.ticker,
        "signal": decision.signal,
        "confidence": decision.confidence,
        "reasoning": decision.reasoning,
        "model_provider": decision.model_provider,
        "model_name": decision.model_name,
        "price": None,
        "limit_price": None,
        "status": status,
        "metadata": {
            **(metadata or {}),
            "strategy_reasoning": getattr(decision, "strategy_reasoning", None),
            "advance_planning_notes": getattr(decision, "advance_planning_notes", None),
            "injected_market_price": getattr(decision, "injected_market_price", None),
        },
        "trade_id": trade_id,
        "embedding": get_embedding(decision.reasoning) if decision.reasoning else None,
    }

    try:
        if decision_id:
            # We explicitly want to update an existing row (Step 13 attribution locking)
            response = client.table("decisions").update(payload).eq("id", decision_id).execute()
        else:
            # New decision or idempotent retry relying on unique constraint
            response = (
                client.table("decisions")
                .upsert(payload, on_conflict="source_id,ticker,signal,model_provider,model_name")
                .execute()
            )

        if not response.data:
            msg = f"Decision for {decision.ticker} saved but no data returned (status={status})."
            logger.error(msg)
            raise RuntimeError(msg)

        return response.data[0]
    except Exception as e:
        logger.error(f"Failed to save decision for {decision.ticker}: {e}")
        raise


async def get_active_ledger_xml(sb_client: Client, owner_id: str) -> str:
    """Fetches the trade history and thesis for currently held positions and formats as XML.

    This provides the agent with context on why positions were originally bought
    and any advance planning notes, preventing the "context black hole" problem.
    """
    async def _exec(builder):
        res = builder.execute()
        if inspect.isawaitable(res):
            return await res
        return res

    # 1. Get portfolio
    p_res = await _exec(sb_client.table("portfolios").select("id").eq("owner_id", owner_id))
    if not p_res.data:
        return ""
    portfolio_id = p_res.data[0]["id"]

    # 2. Get current holdings
    pos_res = await _exec(
        sb_client.table("portfolio_positions")
        .select("ticker, quantity")
        .eq("portfolio_id", portfolio_id)
        .gt("quantity", 0)
    )
    holdings = pos_res.data or []
    if not holdings:
        return ""

    tickers = [h["ticker"] for h in holdings]

    # 3. Get recent executed decisions for these tickers
    dec_res = await _exec(
        sb_client.table("decisions")
        .select("ticker, signal, reasoning, metadata, created_at")
        .eq("model_name", owner_id)
        .eq("status", "EXECUTED")
        .in_("ticker", tickers)
        .order("created_at", desc=True)
        .limit(50)
    )

    decisions_by_ticker = {}
    for d in dec_res.data or []:
        t = d["ticker"]
        if t not in decisions_by_ticker:
            decisions_by_ticker[t] = []
        decisions_by_ticker[t].append(d)

    xml_parts = ["<CURRENT_PORTFOLIO_LEDGER>"]
    for h in holdings:
        t = h["ticker"]
        qty = h["quantity"]
        xml_parts.append(f'  <POSITION ticker="{t}" current_quantity="{qty}">')
        decs = decisions_by_ticker.get(t, [])
        if not decs:
            xml_parts.append("    <HISTORY>No recorded reasoning found.</HISTORY>")
        else:
            # Reverse to show chronological order (oldest to newest)
            decs.reverse()
            for d in decs:
                date_str = d["created_at"].split("T")[0]
                sig = d["signal"]
                reasoning = d["reasoning"] or ""
                metadata = d.get("metadata") or {}
                adv_plan = metadata.get("advance_planning_notes") or ""

                xml_parts.append(f'    <ACTION date="{date_str}" signal="{sig}">')
                if reasoning:
                    xml_parts.append(f"      <REASONING>{reasoning}</REASONING>")
                if adv_plan:
                    xml_parts.append(f"      <ADVANCE_PLANNING>{adv_plan}</ADVANCE_PLANNING>")
                xml_parts.append("    </ACTION>")
        xml_parts.append("  </POSITION>")
    xml_parts.append("</CURRENT_PORTFOLIO_LEDGER>")

    return "\n".join(xml_parts)
